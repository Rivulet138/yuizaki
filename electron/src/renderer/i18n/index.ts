const readStoredLocale = (): string => {
  if (typeof window === 'undefined') return ''
  return window.localStorage.getItem(STORAGE_KEY) || ''
}

export const normalizeLocale = (value?: string | null): Locale => {
  const raw = String(value || '').trim().toLowerCase()
  if (raw.startsWith('en')) return 'en-US'
  if (raw.startsWith('ja') || raw.startsWith('jp')) return 'ja-JP'
  return 'zh-CN'
}

const localeState = reactive<{ locale: Locale }>({
  locale: normalizeLocale(readStoredLocale()),
})

const applyLocale = (locale: Locale) => {
  localeState.locale = locale
  if (typeof window !== 'undefined') {
    window.localStorage.setItem(STORAGE_KEY, locale)
  }
  if (typeof document !== 'undefined') {
    document.documentElement.lang = locale
  }
}

applyLocale(localeState.locale)

export const currentLocale = computed(() => localeState.locale)

export const supportedLocales: Locale[] = ['zh-CN', 'en-US', 'ja-JP']

export const localeLabel = (locale: string): string => {
  const normalized = normalizeLocale(locale)
  if (normalized === 'en-US') return resolvedMessages[localeState.locale]['language.english']
  if (normalized === 'ja-JP') return resolvedMessages[localeState.locale]['language.japanese']
  return resolvedMessages[localeState.locale]['language.zh']
}

export const hasMessage = (key: string, locale: Locale = localeState.locale): key is MessageKey => {
  return Object.prototype.hasOwnProperty.call(resolvedMessages[locale], key)
}

export const t = (key: string, params?: MessageParams): string => {
  const locale = localeState.locale
  const message = hasMessage(key, locale)
    ? resolvedMessages[locale][key]
    : hasMessage(key, 'zh-CN')
      ? resolvedMessages['zh-CN'][key]
      : key

  if (!params) return message

  return Object.entries(params).reduce((text, [paramKey, value]) => {
    return text.split(`{${paramKey}}`).join(String(value ?? ''))
  }, message)
}

export const syncLocaleFromSettings = (value?: string | null): Locale => {
  const locale = normalizeLocale(value || readStoredLocale())
  applyLocale(locale)
  return locale
}

export const setLocale = async (
  value: string,
  options: { persistSettings?: boolean } = {},
): Promise<Locale> => {
  const locale = normalizeLocale(value)
  applyLocale(locale)
  const settingsStore = useSettingsStore()
  settingsStore.state.system.language = locale

  if (options.persistSettings === false) return locale

  await settingsStore.saveSettings({
    system: {
      ...settingsStore.state.system,
      language: locale,
    },
  })

  return locale
}

export const useI18n = () => ({
  hasMessage,
  locale: currentLocale,
  localeLabel,
  normalizeLocale,
  setLocale,
  supportedLocales,
  syncLocaleFromSettings,
  t,
})
